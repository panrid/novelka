package space.panrid.novelka.platform.web;

import java.io.IOException;
import java.util.List;

import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.boot.web.servlet.FilterRegistrationBean;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.http.HttpHeaders;
import org.springframework.web.filter.ShallowEtagHeaderFilter;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.PathItem;
import io.swagger.v3.oas.models.headers.Header;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.media.Content;
import io.swagger.v3.oas.models.media.MediaType;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.responses.ApiResponse;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.servers.Server;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import space.panrid.novelka.platform.SiteProperties;
import space.panrid.novelka.platform.security.BearerTokens;

/**
 * The API's description for developers (етап 22.4): OpenAPI generated by springdoc from the
 * controllers of {@code /api/v1} alone — the site's own JSON stays undocumented and free to change.
 * Served at {@value #PATH} to anyone, cached for five minutes with an ETag. What every operation
 * shares — the optional token, ETag and caching, errors as {@code application/problem+json}, the
 * limits — is added here once rather than on each method. Settings: {@code springdoc.*} in
 * {@code application.yaml}. A committed snapshot ({@code doc/api/openapi-v1.json}) guards against
 * breaking old programs: {@code ApiDescriptionTests}.
 */
@Configuration
class ApiDescription {

    static final String PATH = "/api/v1/openapi.json";
    private static final String TOKEN = "token";
    private static final String PROBLEM = "Problem";

    private static final String ABOUT = """
            Відкритий API Новелки для читалок, ботів, каталогів і агентів ШІ: читання — те саме, що бачать читачі на сайті, —
            і Студія (`/api/v1/studio`) для команд перекладу: глави, оригінал, автопереклад, словник, правки, картинки.
            Сторінка з поясненнями й прикладами: [Для розробників](/developers).

            - **Без входу** можна читати все публічне. З токеном у заголовку `Authorization` (схема `token`) — те, що бачить
              власник токена (наприклад, 18+, якщо він підтвердив вік), у межах прав токена. Токен створюють у «Я → Налаштування → API».
            - **Сторінки за ключем**: у відповіді `next`; передайте його як `after`, щоб отримати наступну. `next: null` — кінець.
            - **Студія** — лише з токеном, і саме з тим правом, яке названо в операції (`studio`, `translate`, `suggest`);
              діють ті самі правила команди, що й на сайті.
            - **Кеш**: кожна відповідь читання має `ETag`; з `If-None-Match` сервер відповідає 304 без тіла.
            - **Частота**: 120 запитів на хвилину з однієї адреси без токена, 600 — на токен; далі 429 з `Retry-After`.
            - **Помилки** — `application/problem+json`, зрозумілий текст українською в `detail`.
            - **Стабільність**: у `/v1` лише додається нове — поля, адреси, необов'язкові параметри. Те, що ламає старі
              програми, з'явиться лише в новій версії.
            """;

    private static final String TOKEN_ABOUT = """
            Токен доступу `nvk_…` з «Я → Налаштування → API». Показується один раз; діє як його власник, але лише в межах прав:
            `read` — публічне читання; `library` — моя бібліотека й прогрес; `suggest` — правки; `studio` — переклади, де я в команді;
            `translate` — автопереклад за мої шаги; `admin` — адміністрування (лише ролям сайту). Для читання досить `read`
            або взагалі без токена; що потрібно Студії — сказано в кожній операції.
            """;

    @Bean
    OpenAPI publicApi(SiteProperties site) {
        return new OpenAPI()
                .info(new Info().title("Новелка API").version("1").description(ABOUT))
                .servers(List.of(new Server().url(site.publicUrl()).description("Новелка")))
                .components(new Components().addSecuritySchemes(TOKEN, new SecurityScheme()
                        .type(SecurityScheme.Type.HTTP).scheme("bearer").bearerFormat("nvk_…").description(TOKEN_ABOUT)))
                // Either without a token at all or with one that has «read».
                .addSecurityItem(new SecurityRequirement())
                .addSecurityItem(new SecurityRequirement().addList(TOKEN, "read"));
    }

    /** What every operation of {@code /api/v1} answers besides its own 200. */
    @Bean
    OpenApiCustomizer publicApiResponses(ObjectProvider<BearerTokens> bearerTokens) {
        return api -> {
            api.getComponents().addSchemas(PROBLEM, problem());
            if (api.getPaths() == null) {
                return;
            }
            BearerTokens tokens = bearerTokens.getIfAvailable();
            api.getPaths().forEach((path, item) -> item.readOperationsMap().forEach((method, operation) -> {
                boolean reading = method == PathItem.HttpMethod.GET;
                // The right a token needs here, from the same rules the security chain applies (TokenScopes):
                // past reading (the Studio's API), a token with that right — the default «none or read» does not do.
                String scope = tokens == null ? null : tokens.scope(method.name(), path);
                if (scope != null && !scope.equals("read")) {
                    operation.setSecurity(List.of(new SecurityRequirement().addList(TOKEN, scope)));
                }
                operation.getResponses().forEach((code, answer) -> {
                    if (code.startsWith("2")) {
                        answer.setDescription("Готово");
                    }
                });
                // Reading answers (not the Studio's) carry an ETag and may be kept a minute.
                boolean cached = reading && (scope == null || scope.equals("read"));
                ApiResponse ok = operation.getResponses().get("200");
                if (ok != null) {
                    if (cached) {
                        ok.addHeaderObject(HttpHeaders.ETAG, header("Відбиток відповіді; передайте його в `If-None-Match`", "\"3f9a1c…\""));
                        ok.addHeaderObject(HttpHeaders.CACHE_CONTROL, header("Скільки можна тримати відповідь: хвилину; `private`, "
                                + "якщо вона залежить від того, хто питає", "public, max-age=60"));
                    }
                }
                if (cached) {
                    operation.getResponses().addApiResponse("304",
                            new ApiResponse().description("Не змінилося з `If-None-Match` — беріть збережену відповідь"));
                }
                operation.getResponses()
                        .addApiResponse("400", failure("Хибний запит: параметр поза межами чи застарілий ключ сторінки"))
                        .addApiResponse("401", failure("Токен недійсний: відкликаний, строк минув або хибний"))
                        .addApiResponse("403", failure("Недоступно: токену бракує потрібного права або це не дозволяє ваша роль у команді"))
                        .addApiResponse("404", failure("Немає такої новели, перекладу чи глави — або вона прихована від того, хто питає"))
                        .addApiResponse("429", failure("Забагато запитів; зачекайте стільки секунд, скільки в `Retry-After`")
                                .addHeaderObject(HttpHeaders.RETRY_AFTER, header("Через скільки секунд можна знову", "12")));
            }));
        };
    }

    /**
     * The description itself may be kept five minutes; its ETag is computed from the bytes. Set before
     * the security headers are written, so they leave {@code Cache-Control} as it is.
     */
    @Bean
    FilterRegistrationBean<ShallowEtagHeaderFilter> apiDescriptionCaching() {
        FilterRegistrationBean<ShallowEtagHeaderFilter> registration = new FilterRegistrationBean<>(new ShallowEtagHeaderFilter() {
            @Override
            protected void doFilterInternal(HttpServletRequest request, HttpServletResponse response, FilterChain chain)
                    throws ServletException, IOException {
                response.setHeader(HttpHeaders.CACHE_CONTROL, "public, max-age=300");
                super.doFilterInternal(request, response, chain);
            }
        });
        registration.addUrlPatterns(PATH);
        return registration;
    }

    private static ApiResponse failure(String description) {
        return new ApiResponse().description(description).content(new Content().addMediaType("application/problem+json",
                new MediaType().schema(new Schema<>().$ref("#/components/schemas/" + PROBLEM))));
    }

    private static Header header(String description, String example) {
        return new Header().description(description).schema(typed("string")).example(example);
    }

    /** RFC 9457, as Spring writes it. */
    private static Schema<?> problem() {
        Schema<?> schema = typed("object").description("Помилка: що сталося — у `detail`, українською, для людини.");
        schema.setRequired(List.of("status", "detail"));
        schema.addProperty("status", typed("integer").description("Код HTTP").example(404));
        schema.addProperty("detail", typed("string").description("Що сталося, зрозуміло для людини").example("Такої глави немає."));
        schema.addProperty("title", typed("string").description("Загальна назва коду HTTP").example("Not Found"));
        schema.addProperty("type", typed("string").description("Вид помилки; зазвичай `about:blank`").example("about:blank"));
        schema.addProperty("instance", typed("string").description("Адреса запиту").example("/api/v1/novels/mag-vody"));
        return schema;
    }

    /** OpenAPI 3.1 reads {@code types}, 3.0 {@code type}: both, so either version writes it. */
    private static Schema<Object> typed(String type) {
        Schema<Object> schema = new Schema<>();
        schema.setType(type);
        schema.addType(type);
        return schema;
    }
}
